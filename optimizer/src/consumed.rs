/// Read by name built at run time (production.rs placement_percent).
fn dynamic(eff: Sym) -> bool {
    eff.starts_with("EFFECT_ADJUST_RIVER_") || eff.ends_with("_ADJACENT_NATURAL_WONDER_PRODUCTION")
}

thread_local!(static SET: HashSet<Sym> = CONSUMED.iter().map(|s| crate::sym::sym(s)).collect());

pub fn is_consumed(eff: Sym) -> bool {
    SET.with(|s| s.contains(&eff)) || dynamic(eff)
}
